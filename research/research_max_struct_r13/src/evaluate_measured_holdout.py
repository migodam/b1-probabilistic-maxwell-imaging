"""Actual measured predictive validation AFTER parent-authorized physics seal.

No holdout archive, prediction material or numerical library is loaded before
validate_seal(require_authorization=True). No material pixel truth is used.
One existing Maxwell LU serves all36 calibrated sources per unique material;
identical materials share explicitly recorded post-seal validation costs.
"""
from __future__ import annotations
import os
for _key in ('OMP_NUM_THREADS','OPENBLAS_NUM_THREADS','MKL_NUM_THREADS','VECLIB_MAXIMUM_THREADS','BLIS_NUM_THREADS'):
    os.environ[_key]='1'
import argparse,csv,json,sys,time,traceback
from pathlib import Path
from datetime import datetime,timezone
try:
    from .seal_results import read,validate_seal
except ImportError:
    from seal_results import read,validate_seal


def utc():return datetime.now(timezone.utc).isoformat()


def write_json(path,value):
    def encode(item):
        if isinstance(item,Path):return str(item)
        if hasattr(item,'item'):return item.item()
        raise TypeError(type(item).__name__)
    Path(path).write_text(json.dumps(value,indent=2,default=encode,allow_nan=False)+'\n')


def write_table(directory,name,rows):
    write_json(directory/(name+'.json'),rows)
    keys=list(dict.fromkeys(key for row in rows for key in row))
    with (directory/(name+'.csv')).open('w',newline='') as stream:
        writer=csv.DictWriter(stream,fieldnames=keys);writer.writeheader()
        for row in rows:
            writer.writerow({k:json.dumps(v) if isinstance(v,(dict,list)) else v for k,v in row.items()})


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root',type=Path,required=True)
    parser.add_argument('--legacy-repo',type=Path,required=True)
    parser.add_argument('--seal',type=Path,required=True)
    parser.add_argument('--out',type=Path,required=True)
    args=parser.parse_args();root=args.root.resolve();out=args.out.resolve()
    began,wall=time.process_time(),time.perf_counter()
    # This guard precedes NumPy/SciPy imports and ALL material/holdout loading.
    seal=read(args.seal);validate_seal(seal,require_authorization=True)
    if Path(seal['root']).resolve()!=root:raise RuntimeError('Requested root differs from reviewed prediction seal')
    cfg=seal['manifest_snapshot']
    if cfg.get('campaign')!='physics_v1' or seal.get('campaign')!='physics_v1':
        raise RuntimeError('Evaluator requires the authorized physics_v1 seal')
    tasks=[t for t in cfg['tasks'] if t.get('family')=='fresnel']
    if len(cfg['tasks'])!=60 or len(tasks)!=14 or len({t['case_id'] for t in tasks})!=2:
        raise RuntimeError('Expected complete60-task physics campaign with two measured inputs and seven methods each')
    expected_methods={'cie','dual_cie','global_dual','dr','ap','event_integer','direct'}
    for cid in {t['case_id'] for t in tasks}:
        case=[t for t in tasks if t['case_id']==cid]
        if len(case)!=7 or {t['method'] for t in case}!=expected_methods:
            raise RuntimeError('Measured method set differs from frozen seven-method contract')
    if any(out.is_relative_to(Path(d['path']).resolve()) for d in seal['directories']):
        raise ValueError('Validation output must be outside sealed result/queue directories')
    expected={t['task_id'] for t in cfg['tasks']}
    accounted={t['task_id'] for t in seal['task_accounting']}
    if expected!=accounted:raise RuntimeError('Seal does not account for every expected physics task')
    guard_CPU=time.process_time()-began;guard_wall=time.perf_counter()-wall
    out.mkdir(parents=True,exist_ok=False)
    authorized_at=utc();import_started=time.process_time();import_wall=time.perf_counter()
    sys.path[:0]=[str(args.legacy_repo.resolve()),str(root/'src')]
    import numpy as np
    from research.research_fbg_r3_experiments.src.physics import MaxwellModel
    import_CPU=time.process_time()-import_started;import_wall_seconds=time.perf_counter()-import_wall
    rows=[];unique=[];setups=[];failures=[];arrays={};holdout_access=[]
    by_case={}
    for task in tasks:by_case.setdefault(task['case_id'],[]).append(task)
    for cid,case_tasks in by_case.items():
        setup_cpu,setup_wall=time.process_time(),time.perf_counter()
        public_path=root/case_tasks[0]['input_file']
        held_spec=case_tasks[0].get('heldout_spec',cfg.get('heldout_specs',{}).get(cid))
        if not held_spec:raise RuntimeError(f'Missing predeclared heldout metadata for {cid}')
        held_path=root/held_spec['path'];context=None;cache=[]
        try:
            # Public G is exactly the training model. Full incident/receiver
            # arrays below were generated by empty-field calibration only.
            with np.load(public_path,allow_pickle=False) as z:
                G=z['G'].copy();shape=tuple(map(int,z['grid_shape']))
                E_training=z['E0'].copy();S_ports=z['S_ports'].copy()
                delta=float(z['delta']);sigma_role=str(z['sigma_role'])
            archive_stat=held_path.stat()
            holdout_access.append(dict(case_id=cid,path=str(held_path.resolve()),
                archive_bytes=archive_stat.st_size,archive_mtime_ns=archive_stat.st_mtime_ns,access_at_utc=utc(),
                authorization_time=authorized_at,authorized_physics_seal=str(args.seal.resolve())))
            with np.load(held_path,allow_pickle=False) as z:
                observed=z[held_spec['measured_values_key']].copy()
                mask=z[held_spec['mask_key']].copy().astype(bool)
                E=z[held_spec['full_incident_key']].copy()
                S=z[held_spec['full_receiver_key']].copy()
            if mask.shape!=(S.shape[0],E.shape[1]) or mask.sum()!=711 or observed.shape!=(711,):
                raise ValueError('Actual measured heldout mask/value dimensions differ from frozen package')
            if E.shape[0]!=G.shape[0] or S.shape[1]!=G.shape[0]:
                raise ValueError('Full calibrated acquisition differs from original model dimensions')
            if not all(np.isfinite(v).all() for v in (G,E,S,observed)):
                raise ValueError('Nonfinite actual calibrated operators or measured heldout values')
            if E.shape[1]!=36 or S.shape[0]!=72:
                raise ValueError('Expected original2001 complete36-source/72-receiver coordinate system')
            # Original2001 split is source indices0,4,...,32. The boolean
            # mask contains actual channels only; absent channels are never
            # zero-filled or turned into observations.
            held_sources=np.arange(0,E.shape[1],4)
            training_sources=np.setdiff1d(np.arange(E.shape[1]),held_sources)
            if not np.array_equal(E[:,training_sources],E_training):
                raise ValueError('Complete calibrated illuminations differ from frozen training model')
            if S_ports.shape!=(27,39,G.shape[0]):
                raise ValueError('Frozen training source-specific port dimensions changed')
            for source,ports in zip(training_sources,S_ports):
                indices=[]
                for receiver_row in ports:
                    matches=np.flatnonzero(np.all(S==receiver_row[None,:],axis=1))
                    if len(matches)!=1:raise ValueError('Full receiver map differs from frozen actual source-specific port')
                    indices.append(int(matches[0]))
                if len(set(indices))!=39 or mask[indices,source].any():
                    raise ValueError('Training and heldout actual receiver maps overlap or duplicate')
            is_held_source=np.broadcast_to(np.isin(np.arange(E.shape[1]),held_sources),mask.shape)[mask]
            model=MaxwellModel(dict(G=G,E0=E,S=S,grid_shape=np.array(shape)))
            context=dict(model=model,observed=observed,mask=mask,is_held_source=is_held_source,
                delta=delta,sigma_role=sigma_role,shape=shape)
            arrays[cid+'__observed_heldout']=observed
            setups.append(dict(case_id=cid,status='COMPLETE',public_input=str(public_path.resolve()),
                heldout_input=str(held_path.resolve()),CPU_seconds=time.process_time()-setup_cpu,
                wall_seconds=time.perf_counter()-setup_wall,operator_import_cost=dict(model.cost),
                G_shape=list(G.shape),complete_E_shape=list(E.shape),complete_S_shape=list(S.shape),
                heldout_channels=int(mask.sum()),heldout_source_channels=int(is_held_source.sum()),
                heldout_receiver_channels=int((~is_held_source).sum()),new_physical_LU=0,new_physical_RHS=0,
                source_convention='R8 exp(-i omega t); original files conjugated by load_file; no new gain/normalization fit',
                calibration='R8 outgoing order2 multipoles fitted only to empty-target measurements',
                missing_measurement_policy='evaluate only true entries of original source-dependent boolean heldout mask',
                full_vs_training_incident_equal=True,full_vs_source_specific_port_rows_equal=True,
                training_heldout_receiver_disjoint=True))
        except Exception as exc:
            failures.append(dict(case_id=cid,stage='SETUP',error=repr(exc)))
            setups.append(dict(case_id=cid,status='FAILED',CPU_seconds=time.process_time()-setup_cpu,
                wall_seconds=time.perf_counter()-setup_wall,error=repr(exc)))
        for task in case_tasks:
            folder=root/'RESULTS'/cfg['campaign']/task['task_id']
            receipt=read(folder/'RECEIPT.json') if (folder/'RECEIPT.json').is_file() else{}
            for view in ('raw','corrected','primary','secondary'):
                effective=view;fallback=False;material_path=folder/(view+'.npz')
                if (view=='secondary' and not material_path.is_file()
                        and receipt.get('secondary_candidate') is None and (folder/'primary.npz').is_file()):
                    effective='primary';fallback=True;material_path=folder/'primary.npz'
                metadata_path=folder/(effective+'.json')
                training=read(metadata_path) if metadata_path.is_file() else{}
                row=dict(case_id=cid,method=task['method'],task_id=task['task_id'],view=view,
                    effective_view=effective,secondary_fallback_to_primary=fallback,
                    run_status=receipt.get('status','MISSING_RECEIPT'),
                    material_source=str(material_path.resolve()),
                    training_Phi=training.get('Phi'),training_D=training.get('D'),training_R=training.get('R'),
                    training_relative_residual=training.get('relative_residual'),
                    training_residual_over_declared_delta=training.get('residual_over_delta'),
                    original_training_noise_feasible_flag=training.get('noise_feasible'),
                    ball_flag_interpretation='membership in fixed .15 model-discrepancy ball; not CN99 noise feasibility',
                    statistical_noise_certificate=False,pixel_GT=False,
                    online_selection_uses_holdout=False,training_metadata_available=metadata_path.is_file(),
                    training_metadata=training)
                if context is None:
                    row.update(status='SETUP_FAILED',holdout_relative_complex_residual=None);rows.append(row);continue
                if not material_path.is_file():
                    row.update(status='NO_PAID_SELECTED_MATERIAL',holdout_relative_complex_residual=None);rows.append(row);continue
                try:
                    with np.load(material_path,allow_pickle=False) as z:m=z['m'].copy().ravel()
                    if m.shape!=(context['model'].n,) or np.iscomplexobj(m) or not np.isfinite(m).all():
                        raise ValueError('Selected material must be original full real finite cell vector')
                    entry=next((item for item in cache if np.array_equal(item['material'],m)),None)
                    if entry is None:
                        ident=f'{cid}__unique_{len(cache):04d}';cpu0,wall0=time.process_time(),time.perf_counter()
                        before=dict(context['model'].cost);prediction=None;validation_error=None;residual=None
                        try:
                            state=context['model'].state(m)
                            prediction=state['Y'][context['mask']].copy()
                            residual=float(state['state_relative_residual'])
                            if prediction.shape!=(711,) or not np.isfinite(prediction).all():
                                raise ValueError('Invalid prediction at actual measured heldout channels')
                        except Exception as exc:validation_error=repr(exc)
                        costs={k:v-before.get(k,0) for k,v in context['model'].cost.items()}
                        entry=dict(material=m.copy(),prediction=prediction,validation_id=ident,
                            status='COMPLETE' if validation_error is None else'FORWARD_FAILED',error=validation_error,
                            CPU_seconds=time.process_time()-cpu0,wall_seconds=time.perf_counter()-wall0,
                            physical_cost=costs,physical_state_relative_residual=residual,references=[])
                        cache.append(entry);unique.append(entry)
                        if prediction is not None:arrays[ident+'__prediction_heldout']=prediction
                    entry['references'].append(dict(case_id=cid,method=task['method'],view=view,task_id=task['task_id']))
                    row.update(status=entry['status'],validation_id=entry['validation_id'],
                        physical_state_relative_residual=entry['physical_state_relative_residual'],
                        validation_error=entry['error'],heldout_channels=711,
                        training_delta=context['delta'],sigma_role=context['sigma_role'])
                    if entry['prediction'] is not None:
                        r=entry['prediction']-context['observed'];split=context['is_held_source']
                        def relative(part):
                            norm=float(np.linalg.norm(context['observed'][part]))
                            return float(np.linalg.norm(r[part])/norm) if norm>0 else None
                        row.update(holdout_relative_complex_residual=relative(np.ones(711,bool)),
                            heldout_source_relative_complex_residual=relative(split),
                            heldout_receiver_relative_complex_residual=relative(~split),
                            heldout_mean_squared_complex_error=float(np.vdot(r,r).real/711))
                    else:row['holdout_relative_complex_residual']=None
                except Exception as exc:
                    row.update(status='SELECTED_MATERIAL_UNAVAILABLE',holdout_relative_complex_residual=None,error=repr(exc))
                    failures.append(dict(case_id=cid,method=task['method'],view=view,stage='MATERIAL',error=repr(exc)))
                rows.append(row)
    ledger=[]
    for entry in unique:
        refs=len(entry['references']);ledger.append({k:v for k,v in entry.items() if k not in ('material','prediction')})
        for row in rows:
            if row.get('validation_id')==entry['validation_id']:
                row.update(shared_validation_reference_count=refs,
                    allocated_validation_CPU_seconds=entry['CPU_seconds']/refs,
                    allocated_validation_wall_seconds=entry['wall_seconds']/refs,
                    allocated_validation_LU_share=entry['physical_cost'].get('LU',0)/refs,
                    allocated_validation_RHS_share=entry['physical_cost'].get('source_RHS',0)/refs,
                    shared_cost_policy='equal split among identical-material method/view references within this object; actual integer work retained once in unique ledger',
                    cost_scope='post-seal heldout validation only; separate from all online cost')
    # Ensure immutable public predictions still match the reviewed seal.
    validate_seal(seal,require_authorization=True)
    write_table(out,'MEASURED_HOLDOUT',rows);write_table(out,'UNIQUE_VALIDATION_COSTS',ledger)
    write_json(out/'SETUP_COSTS.json',setups);write_json(out/'FAILURES.json',failures)
    np.savez_compressed(out/'MEASURED_PREDICTIONS.npz',**arrays)
    write_json(out/'RECEIPT.json',dict(status='COMPLETE' if not failures and all(r['status']=='COMPLETE' for r in rows) else'COMPLETE_WITH_MISSING_OR_FAILED_VIEWS',
        created_at_utc=utc(),authorization_time=authorized_at,seal=str(args.seal.resolve()),
        campaign=cfg['campaign'],expected_tasks=14,expected_view_rows=56,actual_view_rows=len(rows),
        pixel_GT_used=False,material_truth_access=False,heldout_used_for_selection=False,
        holdout_access_log=holdout_access,unique_material_validation_count=len(unique),
        unique_physical_LU=sum(e['physical_cost'].get('LU',0) for e in unique),
        unique_source_RHS=sum(e['physical_cost'].get('source_RHS',0) for e in unique),
        validation_forward_CPU_seconds=sum(e['CPU_seconds'] for e in unique),
        validation_forward_wall_seconds=sum(e['wall_seconds'] for e in unique),
        model_and_input_setup_CPU_seconds=sum(s['CPU_seconds'] for s in setups),
        model_and_input_setup_wall_seconds=sum(s['wall_seconds'] for s in setups),
        dependency_import_CPU_seconds=import_CPU,dependency_import_wall_seconds=import_wall_seconds,
        authorization_guard_CPU_seconds=guard_CPU,authorization_guard_wall_seconds=guard_wall,
        total_evaluator_CPU_seconds=time.process_time()-began,total_evaluator_wall_seconds=time.perf_counter()-wall,
        process_CPU_seconds_near_exit=time.process_time(),
        cache_rule='exact np.array_equal real material vector within same calibrated object; no cross-object reuse or approximate material matching',
        shared_cost_accounting='one integer LU/all36source RHS per unique material; equal reference shares are allocations, not additional solves',
        physical_backend='unchanged existing R4/R3 MaxwellModel using frozen R8 G/fullE0/fullS; one retained LU per unique material',
        observation_policy='711 actual source-dependent heldout channels; no absent-channel zero fill; no fitted gain/new normalization',
        training_ball_qualification='fixed .15||Ytrain|| model discrepancy diagnostic, not known noise/CN99',
        secondary_policy='use saved secondary; if unavailable and receipt has no secondary, primary fallback explicitly flagged',
        cost_scope='all evaluator/setup/validation/export cost separate from online optimization; import/setup and forward costs not additive to reported evaluator total'))
    print(json.dumps(dict(status='MEASURED_POSTSEAL_EVALUATION_COMPLETE',rows=len(rows),unique_materials=len(unique),new_LU=sum(e['physical_cost'].get('LU',0) for e in unique))))


if __name__=='__main__':main()
